"""Shared prose requirements for all narration writers and editors."""

ASD_STYLE_INSTRUCTION = (
    "Use ASD-STE100 principles as a strong guide, with roughly 80 percent "
    "adherence across the prose. Do not claim formal compliance. Prefer "
    "clear, simple words, active constructions, and one main idea per sentence. "
    "Keep terms consistent and technical names exact. Vary sentence length "
    "so the prose has a natural rhythm and does not sound like a repeated "
    "template. Assume the reader can read code but does not know this project. "
    "Use familiar words in place of avoidable jargon. When a technical term "
    "is needed, explain it in plain English before using it; expand acronyms "
    "on first use. Introduce the basic concept before its implementation name. "
    "Do not replace precise terms with vague substitutes. Make only claims "
    "supported by the evidence. Apply these rules to every prose field, "
    "including titles, summaries, the preamble, and closing."
)

WHOLE_STORY_INSTRUCTION = (
    "Edit and organize the complete walkthrough as one document. Keep useful "
    "mechanism detail, direct citations, and a short lead separate from the "
    "required project/basic-concept preamble. Explain concepts before listing "
    "class or field names. Before using `base` or `head`, define them as the "
    "earlier and later compared revisions. Explain that a snapshot is the "
    "captured comparison input with file evidence from those revisions before "
    "using terms such as snapshot validation or input envelope; prefer captured "
    "input to envelope. When `blob ID` or Git blob terminology matters, explain "
    "that it names a stored file-content object linked to the supplied file "
    "text. Explain only concepts needed for this change; do not turn the "
    "preamble into a glossary. Define necessary jargon such as NUL and UTF-8 "
    "at first use. Group formatting and mechanical changes compactly; "
    "explain a mechanism once when a demo and source repeat it. Remove writer "
    "part caveats when the complete document contains the implementation, and "
    "connect each mechanism to its explanation. Keep source warnings honest. "
    "Near the opening, make the quick summary a paired concrete case, not a "
    "mechanism paraphrase. Name one input and its evidence conditions, state "
    "the specific result before the change, then use the same case to state "
    "the specific result after it. Use a case shown by the supplied source; do "
    "not invent input details or outcomes. If no concrete case is established, "
    "label that plainly. Add a short route to mechanism, tests, and "
    "compatibility passages. State an installation or compatibility "
    "consequence only when supplied evidence supports it. In test passages, "
    "say what the test asserts or checks. Keep overall execution status in the "
    "shared verification display and relevant attribution. Do not repeat a "
    "generic not-run or not-verified caveat in each test passage; retain "
    "source-specific uncertainty. Use zero analyzer-verified runs; never invent a model field "
    "for that host-owned value. Quote author-reported checks only as exact "
    "substrings of the supplied description. End with specific remaining "
    "review questions linked to passages and relevant static test IDs. Never "
    "claim execution, equivalence, or behavior that source evidence does not "
    "establish. For a report with about 150 changes and 24 records, aim for "
    "roughly 3,000 narrative words as guidance, not a universal limit. Scale "
    "the length to the evidence and keep the reading path useful."
)

PREAMBLE_INSTRUCTION = (
    "Write a required preamble for the 'Before the code' section. First "
    "introduce the project or relevant part of the system: what it does, "
    "who or what uses it, and the problem it solves, as far as the supplied "
    "evidence establishes. Name the project when the evidence identifies it. "
    "Explain the basic concepts and how they relate "
    "in plain English before discussing the change. Then explain the main "
    "change and the conceptual reading path. Do not assume prior knowledge "
    "of the project. Do not invent project background when it is not known. "
    "Keep this separate from the short introductory sentence and from the "
    "implementation tour. Do not name real files, paths, functions, identifiers, "
    "commands, or source lines in the preamble. This restriction concerns "
    "implementation names, not the known project name. Use conceptual role labels. "
    "Use about 200 to 450 words for a large change when the evidence supports "
    "that length; use less for a small change and do not pad. Separate "
    "paragraphs with a blank line. Allow at most 4,000 characters of prose "
    "and a separate 4,000 characters for complete fenced sketches, including "
    "their fences; keep the total within 8,000 characters. Include one small "
    "conceptual sketch when it helps explain the system or decision, using "
    "a fenced plain-text block marked 'text'. Do not use Mermaid. A two-path "
    "decision sketch has exactly three lines: a short label, then "
    "'├─ condition → outcome' and '└─ condition → outcome'. Other sketches "
    "remain text. Distinguish author-reported goals from source evidence."
)
